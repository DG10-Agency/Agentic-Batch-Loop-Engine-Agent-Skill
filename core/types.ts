export interface LoopConfig {
  /** Path to the input data file (JSON) */
  inputPath: string;
  /** Path to the store the checkpoint/status file */
  checkpointPath: string;
  /** Concurrency level (default: 1) */
  concurrency?: number;
  /** Max retries per item (default: 3) */
  maxRetries?: number;
  /** Timeout in ms per item. If exceeded, item fails. (default: no timeout) */
  itemTimeoutMs?: number;
  /** Optional: Direct array of input data instead of loading from a file */
  inputData?: any[];
  /** Optional: progress callback, invoked every `progressEvery` settled items (and once at the end) */
  onProgress?: (done: number, total: number) => void;
  /** Items between onProgress calls (default: 100) */
  progressEvery?: number;
}

export type ItemStatus = 'pending' | 'processing' | 'completed' | 'failed' | 'awaiting_agent';

export interface BatchItem<T = any> {
  id: string;
  data: T;
  status: ItemStatus;
  attempts: number;
  lastError?: string;
  pendingPrompt?: any;
  output?: any;
  logs?: string[];
  /** Count of oldest log entries dropped by the per-item log cap (100k-scale bound) */
  logsDropped?: number;
}

export interface Checkpoint<T = any> {
  jobId: string;
  startTime: string;
  /** Schema version of this checkpoint file (old files without it load as 0) */
  stateVersion: number;
  items: BatchItem<T>[];
  completedCount: number;
  failedCount: number;
  /** NEW: Signifies that the job is complete and ready for cleanup */
  cleanupReady?: boolean;
  /** NEW: List of files generated by this job that can be cleaned up */
  cleanupFiles?: string[];
}

export interface WorkerContext {
  log: (message: string) => void;
}

export type WorkerFunction<T = any, R = any> = (
  item: T,
  context: WorkerContext
) => Promise<R>;
